import pytest
from datetime import date, timedelta, datetime

from . import data_service

def make_iso(d: date) -> str:
    # returns ISO format with time to match repo data
    return datetime.combine(d, datetime.min.time()).isoformat()


def test_get_number_active_members(monkeypatch):
    monkeypatch.setattr(data_service, 'getNumberActiveMembersFromRepo', lambda: [{"status": "active"}, {"status": "active"}, {"status": "active"}])
    assert data_service.getNumberActiveMembers() == 3


def test_get_member_types_data(monkeypatch):
    # 2 Basic, 1 VIP
    sample = [
        {'tier': 'Basic'},
        {'tier': 'VIP'},
        {'tier': 'Basic'},
    ]
    monkeypatch.setattr(data_service, 'getMemberTypesDataFromRepo', lambda: sample)
    tiers, counts = data_service.getMemberTypesData()

    # have to convert back to dictionary because the exact order generated by Counter is not predictable
    result = dict(zip(tiers, counts))
    assert result == {'Basic': 2, 'VIP': 1}


def test_get_class_popularity(monkeypatch):
    sample = [
        {'class_name': 'Yoga', 'total_bookings': 10},
        {'class_name': 'Boxing', 'total_bookings': 30},
        {'class_name': 'Yoga', 'total_bookings': 5},
    ]
    monkeypatch.setattr(data_service, 'getClassNamesFromRepo', lambda: sample)
    names, counts = data_service.getClassPopularityData()

    # most popular (top of list) is Boxing
    assert names[0] == 'Boxing'
    assert counts[0] == 30

    # Yoga is 10 + 5 = 15
    assert 'Yoga' in names and counts[names.index('Yoga')] == 15


